// Nested arrays: one extraction level per array
// ---------------------------------------------------------------------------

// An array one level below a section root — anywhere under an object
// section's subtree, or directly inside a top-level array's row items. Each
// gets a Row/Rows component pair in its section file; arrays any deeper
// stay TODO comments (one extraction level is generated per array).
type NestedArrayEntry = Readonly<{
  key: string; // body-walker lookup: full dot path / row item field name
  stem: string; // deduped identifier stem: {stem}Row, {stem}Rows, empty{stem}Item
  label: string;
  item: FieldSpec;
  // The list path, three ways: the useXFieldArray argument (static string,
  // or a backtick template when the parent is an array row), the template
  // text row paths extend with `.${index}...`, and raw text for comments.
  listArg: string;
  templateBase: string;
  commentBase: string;
  itemTypeExpr: string;
  // The ancestor row-index prop names threaded into this array's Row/Rows
  // (p0, p1, ... — one per enclosing array row). Empty for an array under an
  // object section (a static path); [p0] one level inside an array row; [p0,
  // p1] two levels in, and so on. Every bound path interpolates these plus
  // the Row's own `index`.
  holes: readonly string[];
}>;

type RawNestedArray = Readonly<{
  segments: readonly string[];
  label: string;
  item: FieldSpec;
}>;

// Addressable arrays anywhere under an object section's fields. Objects do
// not consume an extraction level; each array does, so the walk stops there.
// Mirrors the body walker's FieldPath boundary: no Rows pair for an array
// whose list path exceeds the budget, nor under an object the body TODOs.
const collectNestedArrays = (
  fields: readonly NamedField[],
  segments: readonly string[],
): readonly RawNestedArray[] =>
  fields.flatMap((field): readonly RawNestedArray[] => {
    if (isUnaddressable(field.name)) return [];
    const at = [...segments, field.name];
    switch (field.spec.kind) {
      case "object":
        return overDepthBudget(field.spec, at.length)
          ? []
          : collectNestedArrays(field.spec.fields, at);
      case "array":
        return overDepthBudget(field.spec, at.length)
          ? []
          : [{ segments: at, label: field.label, item: field.spec.item }];
      default:
        return [];
    }
  });

// Static-path entries for an object section (segments include the section
// key). The item type folds NonNullable over every segment, mirroring the
// single-file backends' item type exprs.
const objectNestedEntries = (
  naming: Naming,
  raws: readonly RawNestedArray[],
): readonly NestedArrayEntry[] =>
  raws.reduce<
    Readonly<{
      used: ReadonlySet<string>;
      entries: readonly NestedArrayEntry[];
    }>
  >(
    (acc, raw) => {
      const base = pascalCase(raw.segments[raw.segments.length - 1] ?? "");
      const stem = `${base}${identifierSuffix(base, acc.used)}`;
      const path = raw.segments.join(".");
      return {
        used: new Set([...acc.used, stem]),
        entries: [
          ...acc.entries,
          {
            key: path,
            stem,
            label: raw.label,
            item: raw.item,
            listArg: q(path),
            templateBase: templateEscape(path),
            commentBase: path,
            itemTypeExpr: `${raw.segments.reduce(
              (expr, segment) => `NonNullable<${expr}[${q(segment)}]>`,
              naming.valuesType,
            )}[number]`,
            holes: [],
          },
        ],
      };
    },
    { used: new Set<string>(), entries: [] },
  ).entries;

// Parent-indexed entries for arrays directly inside an array section's row
// items: the first hole (p0) is the enclosing section row's index, so every
// bound path opens with two numeric holes and deeper levels recurse from here.
const arrayNestedEntries = (
  naming: Naming,
  sectionKey: string,
  sectionStem: string,
  itemFields: readonly NamedField[],
): readonly NestedArrayEntry[] =>
  itemFields
    .flatMap((field) =>
      !isUnaddressable(field.name) && field.spec.kind === "array"
        ? [{ field, item: field.spec.item }]
        : [],
    )
    .reduce<
      Readonly<{
        used: ReadonlySet<string>;
        entries: readonly NestedArrayEntry[];
      }>
    >(
      (acc, { field, item }) => {
        const base = `${sectionStem}${pascalCase(field.name)}`;
        const stem = `${base}${identifierSuffix(base, acc.used)}`;
        const templateBase = `${templateEscape(sectionKey)}.\${p0}.${templateEscape(field.name)}`;
        return {
          used: new Set([...acc.used, stem]),
          entries: [
            ...acc.entries,
            {
              key: field.name,
              stem,
              label: field.label,
              item,
              listArg: `\`${templateBase}\``,
              templateBase,
              commentBase: `${sectionKey}.$\{p0}.${field.name}`,
              itemTypeExpr: `NonNullable<NonNullable<${naming.valuesType}[${q(sectionKey)}]>[number][${q(field.name)}]>[number]`,
              holes: ["p0"],
            },
          ],
        };
      },
      { used: new Set<string>([sectionStem]), entries: [] },
    ).entries;

// The labeled wrapper around a nested list — the section keeps the outer
// chrome, this is just a subheading plus container.
const nestedListShell = (
  ui: ModuleUi,
  label: string,
): Readonly<{
  imports: readonly ImportLine[];
  open: readonly string[];
  close: readonly string[];
}> => {
  switch (ui) {
    case "antd":
      return {
        imports: [{ from: "antd", names: ["Flex", "Typography"] }],
        open: [
          `    <Flex vertical gap="middle">`,
          `      <Typography.Title level={5}>${jsxText(label)}</Typography.Title>`,
        ],
        close: ["    </Flex>"],
      };
    case "mantine":
      return {
        imports: [{ from: "@mantine/core", names: ["Stack", "Title"] }],
        open: [
          `    <Stack gap="md">`,
          `      <Title order={5}>${jsxText(label)}</Title>`,
        ],
        close: ["    </Stack>"],
      };
    case "chakra":
      return {
        imports: [{ from: "@chakra-ui/react", names: ["Heading", "Stack"] }],
        open: [
          `    <Stack gap="4">`,
          `      <Heading size="xs">${jsxText(label)}</Heading>`,
        ],
        close: ["    </Stack>"],
      };
    case "mui":
      return {
        imports: [{ from: "@mui/material", names: ["Stack", "Typography"] }],
        open: [
          "    <Stack spacing={2}>",
          `      <Typography variant="subtitle2">${jsxText(label)}</Typography>`,
        ],
        close: ["    </Stack>"],
      };
    case "shadcn":
      return {
        imports: [],
        open: [
          `    <div className="grid gap-3">`,
          `      <h4 className="text-sm font-medium">${jsxText(label)}</h4>`,
        ],
        close: ["    </div>"],
      };
    case "plain":
      return {
        imports: [],
        open: ["    <fieldset>", `      <legend>${jsxText(label)}</legend>`],
        close: ["    </fieldset>"],
      };
  }
};

// The Row/Rows pair a nested array compiles to — and, recursively, a pair for
// every array nested inside its item, to arbitrary depth. Each level threads
// the enclosing rows' indices as props (p0, p1, ...); a bound path carries one
// hole per enclosing array plus the Row's own `index`. `used` dedupes
// component stems across the whole tree. The IR is finite (--max-depth), so
// the recursion always terminates. Non-array, non-scalar shapes inside a row
// (nested objects, unions, tuples) stay TODO comments.
type NestedParts = Readonly<{
  lines: readonly string[];
  imports: readonly ImportLine[];
}>;

const nestedArrayComponents = (
  ui: ModuleUi,
  naming: Naming,
  entry: NestedArrayEntry,
  used: Set<string>,
): NestedParts => {
  const rowName = `${entry.stem}Row`;
  const rowsName = `${entry.stem}Rows`;
  const emptyName = `empty${entry.stem}Item`;
  const shell = arrayShell(ui, entry.label);
  const wrap = nestedListShell(ui, entry.label);
  const scalarItem = isScalarSpec(entry.item);
  // Options props consumed anywhere in this entry's item subtree: Rows and
  // Row both declare them, references pass them through from the enclosing
  // scope, and each child ref forwards its own subset — so the chain
  // composes to any nesting depth.
  const entryOptionsProps = rowItemOptionsProps(entry.item);

  // This row's own index becomes the next hole for arrays extracted from it.
  const rowIndexHole = `p${entry.holes.length}`;

  // FieldPath budget accounting for this entry's rows: the row path is one
  // segment past the (already-validated) list template; a named field or a
  // child array's list adds one more.
  const rowSegments = pathSegmentCount(entry.templateBase) + 1;

  // The one production of an over-budget row-field TODO (shared by every
  // item-field kind — scalar bindings, child lists, and nested containers
  // degrade identically).
  const overBudgetFieldBody = (fieldName: string): readonly string[] => [
    depthTodoLine(`${entry.commentBase}.$\{index}.${fieldName}`, "      "),
  ];
  const overBudgetRowBody = (): readonly string[] => [
    depthTodoLine(`${entry.commentBase}.$\{index}`, "      "),
  ];

  // The entry for an array extracted from this row (one deeper hole), claiming
  // a unique stem. fieldName undefined => the item itself is an array.
  const childEntry = (
    fieldName: string | undefined,
    label: string,
    item: FieldSpec,
    elemTypeExpr: string,
  ): NestedArrayEntry => {
    const baseStem =
      fieldName === undefined
        ? `${entry.stem}Item`
        : `${entry.stem}${pascalCase(fieldName)}`;
    const stem = `${baseStem}${identifierSuffix(baseStem, used)}`;
    used.add(stem);
    const tail = fieldName === undefined ? "" : `.${templateEscape(fieldName)}`;
    const commentTail = fieldName === undefined ? "" : `.${fieldName}`;
    const templateBase = `${entry.templateBase}.\${${rowIndexHole}}${tail}`;
    return {
      key: fieldName ?? "",
      stem,
      label,
      item,
      listArg: `\`${templateBase}\``,
      templateBase,
      commentBase: `${entry.commentBase}.$\{${rowIndexHole}}${commentTail}`,
      itemTypeExpr: elemTypeExpr,
      holes: [...entry.holes, rowIndexHole],
    };
  };

  // <ChildRows p0={p0} ... pN={index} /> — this row's ancestors plus its
  // index, plus the child subtree's options props (in scope on this Row).
  const childRef = (child: NestedArrayEntry): string =>
    `      <${child.stem}Rows ${[
      ...entry.holes.map((h) => `${h}={${h}}`),
      `${rowIndexHole}={index}`,
    ].join(" ")}${optionsPropsAttrs(rowItemOptionsProps(child.item))} />`;

  const dynamicId = (name: string | undefined): string =>
    name === undefined
      ? `{\`${entry.templateBase}.\${index}\`}`
      : `{\`${entry.templateBase}.\${index}.${templateEscape(name)}\`}`;

  // Per-field pieces of an object item: a scalar leaf (with its binding
  // lines — the field hook plus, for kit numbers, the hoisted number-props
  // hook — and import spec), an extracted <ChildRows /> (recursed), or a
  // TODO.
  type Piece = Readonly<{
    body: readonly string[];
    bindings?: readonly string[];
    spec?: FieldSpec;
    part?: NestedParts;
  }>;
  const rowVarUsed = new Set<string>([
    ...entry.holes,
    "index",
    "onRemove",
    "field",
    "rows",
  ]);
  const leafVar = (name: string, spec: FieldSpec): string => {
    // camelIdent, not camelCase: a field named "new"/"delete" would otherwise
    // emit a reserved-word const declaration. Number leaves reserve their
    // hoisted `${var}NumberProps` const too (numberPropsBindings emits it),
    // so a sibling field named like the derived const can't collide.
    const base = camelIdent(name).length === 0 ? "value" : camelIdent(name);
    const { varName, reserved } = allocateBindingVar(
      base,
      spec.kind === "number",
      rowVarUsed,
    );
    reserved.forEach((n) => rowVarUsed.add(n));
    return varName;
  };
  const objectPieces: readonly Piece[] =
    entry.item.kind === "object"
      ? entry.item.fields.map((field): Piece => {
          if (isUnaddressable(field.name)) {
            return {
              body: [
                `      {/* TODO: field ${commentText(q(field.name))} skipped — "." in a key is not path-addressable (see formstand docs) */}`,
              ],
            };
          }
          // Every field of a row sits one segment past the row path — past
          // the budget nothing binds (a scalar's useField, a child list's
          // useFieldArray, a container's hand-extraction), so all kinds
          // degrade to the same depth TODO.
          if (overDepthBudget(field.spec, rowSegments + 1)) {
            return { body: overBudgetFieldBody(field.name) };
          }
          if (isScalarSpec(field.spec)) {
            const varName = leafVar(field.name, field.spec);
            return {
              body: leafControl(
                ui,
                field.spec,
                varName,
                jsxText(field.label),
                dynamicId(field.name),
                "      ",
              ),
              bindings: [
                `  const ${varName} = ${naming.hook("Field")}(\`${entry.templateBase}.\${index}.${templateEscape(field.name)}\`);`,
                ...numberPropsBindings(ui, [{ varName, spec: field.spec }]),
              ],
              spec: field.spec,
            };
          }
          if (field.spec.kind === "array") {
            const child = childEntry(
              field.name,
              field.label,
              field.spec.item,
              `NonNullable<(${entry.itemTypeExpr})[${q(field.name)}]>[number]`,
            );
            return {
              body: [childRef(child)],
              part: nestedArrayComponents(ui, naming, child, used),
            };
          }
          return {
            body: [
              `      {/* TODO: nested ${field.spec.kind} ${commentText(q(`${entry.commentBase}.$\{index}.${field.name}`))} — bind it by hand */}`,
            ],
          };
        })
      : [];

  // The row's bindings, body, leaf import-specs, and recursed child parts,
  // by item kind: object (its fields), scalar (one leaf), array-of-arrays
  // (recurse the inner array), or tuple/union (a TODO).
  const parts: Readonly<{
    bindings: readonly string[];
    body: readonly string[];
    specs: readonly FieldSpec[];
    children: readonly NestedParts[];
  }> =
    entry.item.kind === "object"
      ? {
          bindings: objectPieces.flatMap((p) => p.bindings ?? []),
          body: objectPieces.flatMap((p) => p.body),
          specs: objectPieces.flatMap((p) => (p.spec ? [p.spec] : [])),
          children: objectPieces.flatMap((p) => (p.part ? [p.part] : [])),
        }
      : overDepthBudget(entry.item, rowSegments)
        ? {
            // The row path itself is past the budget (for an array item the
            // inner list IS the row path; a tuple/union needs headroom for
            // its positions/discriminant): the list hook still binds, but
            // each row degrades to the depth TODO — extraction or binding
            // by hand is impossible within the budget.
            bindings: [],
            body: overBudgetRowBody(),
            specs: [],
            children: [],
          }
        : scalarItem
          ? {
              bindings: [
                `  const field = ${naming.hook("Field")}(\`${entry.templateBase}.\${index}\`);`,
                ...numberPropsBindings(ui, [
                  { varName: "field", spec: entry.item },
                ]),
              ],
              body: leafControl(
                ui,
                entry.item,
                "field",
                jsxText(entry.label),
                dynamicId(undefined),
                "      ",
              ),
              specs: [entry.item],
              children: [],
            }
          : entry.item.kind === "array"
            ? ((): typeof parts => {
                const child = childEntry(
                  undefined,
                  entry.label,
                  entry.item.item,
                  `NonNullable<${entry.itemTypeExpr}>[number]`,
                );
                return {
                  bindings: [],
                  body: [childRef(child)],
                  specs: [],
                  children: [nestedArrayComponents(ui, naming, child, used)],
                };
              })()
            : {
                bindings: [],
                body: [
                  `      {/* TODO: array item is a ${entry.item.kind} in ${commentText(q(entry.commentBase))} rows — bind it by hand */}`,
                ],
                specs: [],
                children: [],
              };

  const holeParams = entry.holes.map((h) => `  ${h},`);
  const holeTypes = entry.holes.map((h) => `${h}: number`);
  const optionsParams = entryOptionsProps.map((name) => `  ${name},`);
  const optionsTypes = optionsPropsTypeFields(entryOptionsProps);

  const lines = [
    // Children are declared before the Row that references them.
    ...parts.children.flatMap((part) => [...part.lines, ""]),
    blankNeedsCast(entry.item)
      ? `const ${emptyName} = ${emitInitialValues(entry.item, 0)} as unknown as ${entry.itemTypeExpr};`
      : `const ${emptyName}: ${entry.itemTypeExpr} = ${emitInitialValues(entry.item, 0)};`,
    "",
    `const ${rowName} = ({`,
    ...holeParams,
    "  index,",
    "  onRemove,",
    ...optionsParams,
    `}: Readonly<{ ${[...holeTypes, "index: number", "onRemove: () => void", ...optionsTypes].join("; ")} }>) => {`,
    ...parts.bindings,
    "  return (",
    ...shell.rowOpen,
    ...parts.body,
    ...shell.rowClose("onRemove"),
    "  );",
    "};",
    "",
    ...(entry.holes.length === 0 && entryOptionsProps.length === 0
      ? [`const ${rowsName} = () => {`]
      : [
          `const ${rowsName} = ({`,
          ...holeParams,
          ...optionsParams,
          `}: Readonly<{ ${[...holeTypes, ...optionsTypes].join("; ")} }>) => {`,
        ]),
    `  const rows = ${naming.hook("FieldArray")}(${entry.listArg});`,
    "  return (",
    ...wrap.open,
    "      {rows.fields.map((row, index) => (",
    `        <${rowName}`,
    "          key={row.id}",
    ...entry.holes.map((h) => `          ${h}={${h}}`),
    "          index={index}",
    "          onRemove={() => rows.remove(index)}",
    ...entryOptionsProps.map((name) => `          ${name}={${name}}`),
    "        />",
    "      ))}",
    ...shell.listError,
    ...shell.addButton(
      `() => rows.push(${emptyName})`,
      `Add ${entry.label.toLowerCase()}`,
    ),
    ...wrap.close,
    "  );",
    "};",
  ];

  return {
    lines,
    imports: [
      ...parts.specs.flatMap((s) => leafImports(ui, s)),
      ...shell.imports,
      ...wrap.imports,
      ...parts.children.flatMap((part) => part.imports),
    ],
  };
};

const objectSectionFile = (
  ui: ModuleUi,
  visual: VisualOptions,
  naming: Naming,
  section: SectionPlan,
  plan: Plan,
): ModuleFile => {
  const spec = section.spec as ObjectSpec;
  const propsType = `${section.componentName}Props`;
  const hookName = `use${section.componentName}`;
  const own = (segments: readonly string[]): FieldPlan | undefined =>
    plan.fields.find((f) => f.segments.join(".") === segments.join("."));

  // Arrays anywhere under this section each get a Row/Rows pair in this
  // file; the body renders <XRows /> at the array's site.
  const nested = objectNestedEntries(
    naming,
    collectNestedArrays(spec.fields, [section.key]),
  );
  const nestedByKey = new Map(nested.map((entry) => [entry.key, entry]));
  // One shared stem registry so recursively-extracted child components never
  // collide with each other or with the top-level entries.
  const nestedUsed = new Set<string>(nested.map((entry) => entry.stem));
  const nestedParts = nested.map((entry) =>
    nestedArrayComponents(ui, naming, entry, nestedUsed),
  );

  const body = (
    fields: readonly NamedField[],
    segments: readonly string[],
    indent: string,
  ): readonly string[] =>
    fields.flatMap((field): readonly string[] => {
      if (isUnaddressable(field.name)) {
        return [
          `${indent}{/* TODO: field ${commentText(q(field.name))} skipped — "." in a key is not path-addressable (see formstand docs) */}`,
        ];
      }
      const at = [...segments, field.name];
      // The FieldPath boundary first, for EVERY kind — same order as the
      // single-file walker, so an over-budget union/tuple degrades to the
      // depth TODO (its hand-binding advice would be unachievable) and the
      // CLI warning list mirrors the emitted TODOs exactly.
      if (overDepthBudget(field.spec, at.length)) {
        return [depthTodoLine(at.join("."), indent)];
      }
      switch (field.spec.kind) {
        case "object":
          return [
            `${indent}<fieldset${
              visual.columns > 1
                ? ui === "shadcn"
                  ? ` className="md:col-span-full"`
                  : ` style={{ gridColumn: "1 / -1" }}`
                : ""
            }>`,
            `${indent}  <legend>${jsxText(field.label)}</legend>`,
            ...body(field.spec.fields, at, `${indent}  `),
            `${indent}</fieldset>`,
          ];
        case "array": {
          const entry = nestedByKey.get(at.join("."));
          return entry === undefined
            ? [
                `${indent}{/* TODO: nested array ${commentText(q(at.join(".")))} — extract a row component with its own ${naming.hook("FieldArray")} */}`,
              ]
            : [
                `${indent}<${entry.stem}Rows${optionsPropsAttrs(rowItemOptionsProps(entry.item))} />`,
              ];
        }
        case "union":
          // A union nested inside an object section: only top-level unions
          // get a generated section; deeper ones are left to extract by hand.
          return [
            `${indent}{/* TODO: discriminated union ${commentText(q(at.join(".")))} — only top-level unions are generated; bind the discriminant with ${naming.hook("Field")} and its variant fields with ${naming.hook("VariantField")} */}`,
          ];
        case "tuple":
          // Only a top-level tuple gets a generated section; a nested one is
          // left to bind by hand at its positional paths.
          return [
            `${indent}{/* TODO: tuple ${commentText(q(at.join(".")))} — only a top-level tuple is generated; bind its elements by hand with ${naming.hook("Field")} at .0, .1, ... */}`,
          ];
        default: {
          // Over-budget scalars were never planned (collectLeaves skips
          // them) — the guard above already emitted their TODO. Overridden
          // fields get their options prop threaded through.
          const planned = own(at);
          return planned === undefined
            ? []
            : [
                `${indent}<${planned.componentName}${optionsPropsAttrs(leafOptionsProp(planned.spec))} />`,
              ];
        }
      }
    });

  const fieldImports = collectLeaves(spec.fields, [section.key])
    .map(({ segments }) => own(segments))
    .flatMap((planned) => (planned === undefined ? [] : [planned]))
    .map(
      (planned) =>
        `import { ${planned.componentName} } from "../fields/${planned.componentName}";`,
    );

  // Nested rows bind template paths and push typed empty items, so the file
  // gains the bound Field/FieldArray hooks and the draft values type.
  const hooksImports =
    nested.length === 0
      ? [
          `import { ${naming.hook("IsDirty")}, ${naming.hook("IsValid")} } from "../hooks";`,
        ]
      : [
          "import {",
          `  ${naming.hook("Field")},`,
          `  ${naming.hook("FieldArray")},`,
          `  ${naming.hook("IsDirty")},`,
          `  ${naming.hook("IsValid")},`,
          `} from "../hooks";`,
          `import type { ${naming.valuesType} } from "../types";`,
        ];

  // Options props consumed anywhere under this section (field files and
  // nested rows): declared here, passed in by the form file.
  const sectionProps = sectionOptionsProps(spec);
  const sectionPropsTypeFields = [
    "heading?: string",
    ...optionsPropsTypeFields(sectionProps),
  ];

  return {
    path: `sections/${section.componentName}.tsx`,
    content: [
      HEADER,
      ...mergeImports([
        ...objectSectionImports(ui, visual),
        ...nestedParts.flatMap((part) => part.imports),
      ]),
      ...hooksImports,
      ...fieldImports,
      "",
      `export type ${propsType} = Readonly<{ ${sectionPropsTypeFields.join("; ")} }>;`,
      "",
      "// The section hook is the path-scoped flags: dirty/valid for this",
      "// subtree only, as boolean-only subscriptions.",
      `export const ${hookName} = () => ({`,
      `  dirty: ${naming.hook("IsDirty")}(${q(section.key)}),`,
      `  valid: ${naming.hook("IsValid")}(${q(section.key)}),`,
      "});",
      "",
      ...nestedParts.flatMap((part) => [...part.lines, ""]),
      `export const ${section.componentName} = ({`,
      `  heading = ${q(section.label)},`,
      ...sectionProps.map((name) => `  ${name},`),
      `}: ${propsType}) => {`,
      `  const { dirty, valid } = ${hookName}();`,
      "  return (",
      ...objectShell(ui, visual, body(spec.fields, [section.key], "      ")),
      "  );",
      "};",
      "",
    ].join("\n"),
  };
};

// A tuple compiles to a section whose body is fixed positional leaves, each
// bound at a STATIC numeric-index path (coord.0, coord.1) — no useFieldArray,
// no add/remove, the arity is fixed. Non-scalar elements degrade to a TODO.
const tupleSectionFile = (
  ui: ModuleUi,
  visual: VisualOptions,
  naming: Naming,
  section: SectionPlan,
): ModuleFile => {
  const spec = section.spec as Extract<FieldSpec, Readonly<{ kind: "tuple" }>>;
  const propsType = `${section.componentName}Props`;
  const hookName = `use${section.componentName}`;

  const used = new Set<string>(["dirty", "valid", "heading"]);
  const elements = spec.elements.map((element, index) => {
    const base = `element${index}`;
    // Number elements reserve their hoisted `${var}NumberProps` const too
    // (numberPropsBindings emits it next to the field hooks).
    const { varName, reserved } = allocateBindingVar(
      base,
      element.kind === "number",
      used,
    );
    reserved.forEach((n) => used.add(n));
    return { element, index, varName, scalar: isScalarSpec(element) };
  });
  const scalarElements = elements.filter((e) => e.scalar);

  const bindings = scalarElements.map(
    ({ varName, index }) =>
      `  const ${varName} = ${naming.hook("Field")}(${q(`${section.key}.${index}`)});`,
  );

  const bodyLines = elements.flatMap(({ element, index, varName, scalar }) =>
    scalar
      ? leafControl(
          ui,
          element,
          varName,
          jsxText(`${section.label} ${index + 1}`),
          `{${q(`${section.key}.${index}`)}}`,
          "      ",
        )
      : [
          `      {/* TODO: tuple element ${index} (${element.kind}) at ${commentText(q(`${section.key}.${index}`))} isn't scalar — bind it by hand */}`,
        ],
  );

  return {
    path: `sections/${section.componentName}.tsx`,
    content: [
      HEADER,
      ...mergeImports([
        ...objectSectionImports(ui, visual),
        ...scalarElements.flatMap((e) => leafImports(ui, e.element)),
      ]),
      scalarElements.length > 0
        ? `import { ${naming.hook("Field")}, ${naming.hook("IsDirty")}, ${naming.hook("IsValid")} } from "../hooks";`
        : `import { ${naming.hook("IsDirty")}, ${naming.hook("IsValid")} } from "../hooks";`,
      "",
      `export type ${propsType} = Readonly<{ heading?: string }>;`,
      "",
      "// The section hook is the path-scoped flags: dirty/valid for this",
      "// subtree only, as boolean-only subscriptions.",
      `export const ${hookName} = () => ({`,
      `  dirty: ${naming.hook("IsDirty")}(${q(section.key)}),`,
      `  valid: ${naming.hook("IsValid")}(${q(section.key)}),`,
      "});",
      "",
      `export const ${section.componentName} = ({`,
      `  heading = ${q(section.label)},`,
      `}: ${propsType}) => {`,
      `  const { dirty, valid } = ${hookName}();`,
      ...bindings,
      ...numberPropsBindings(
        ui,
        scalarElements.map(({ varName, element }) => ({
          varName,
          spec: element,
        })),
      ),
      "  return (",
      ...objectShell(ui, visual, bodyLines),
      "  );",
      "};",
      "",
    ].join("\n"),
  };
};

const arraySectionFile = (
  ui: ModuleUi,
  visual: VisualOptions,
  naming: Naming,
  section: SectionPlan,
): ModuleFile => {
  const spec = section.spec as Extract<FieldSpec, Readonly<{ kind: "array" }>>;
  const propsType = `${section.componentName}Props`;
  const hookName = `use${section.componentName}`;
  const sectionStem = section.componentName.replace(/Section$/, "");
  const rowName = `${sectionStem}Row`;
  const emptyName = `empty${sectionStem}Item`;
  const shell = arrayShell(ui, section.label);
  const itemLeaves =
    spec.item.kind === "object"
      ? spec.item.fields.filter(
          (field) => !isUnaddressable(field.name) && isScalarSpec(field.spec),
        )
      : [];

  // Arrays directly inside this array's row items each get their own
  // Row/Rows pair, threaded the parent row's index (two numeric holes in
  // every bound path). Nested objects keep their TODO.
  const nested = arrayNestedEntries(
    naming,
    section.key,
    sectionStem,
    spec.item.kind === "object" ? spec.item.fields : [],
  );
  const nestedByKey = new Map(nested.map((entry) => [entry.key, entry]));
  const nestedUsed = new Set<string>(nested.map((entry) => entry.stem));
  const nestedParts = nested.map((entry) =>
    nestedArrayComponents(ui, naming, entry, nestedUsed),
  );

  // An array whose row item is ITSELF an array (an array-of-arrays section):
  // the inner array extracts to its own recursive Row/Rows pair, threaded the
  // section row's index as p0. (Object-item nested arrays are handled above.)
  const arrayItemEntry: NestedArrayEntry | undefined =
    spec.item.kind === "array"
      ? ((): NestedArrayEntry => {
          const base = `${sectionStem}Item`;
          const stem = `${base}${identifierSuffix(base, nestedUsed)}`;
          nestedUsed.add(stem);
          const templateBase = `${templateEscape(section.key)}.\${p0}`;
          return {
            key: "",
            stem,
            label: section.label,
            item: spec.item.item,
            listArg: `\`${templateBase}\``,
            templateBase,
            commentBase: `${section.key}.$\{p0}`,
            itemTypeExpr: `NonNullable<NonNullable<${naming.valuesType}[${q(section.key)}]>[number]>[number]`,
            holes: ["p0"],
          };
        })()
      : undefined;
  const allNestedParts = [
    ...nestedParts,
    ...(arrayItemEntry === undefined
      ? []
      : [nestedArrayComponents(ui, naming, arrayItemEntry, nestedUsed)]),
  ];

  const itemExtras =
    spec.item.kind === "object"
      ? spec.item.fields.flatMap((field) => {
          if (isUnaddressable(field.name)) {
            return [
              `      {/* TODO: field ${commentText(q(field.name))} skipped — "." in a key is not path-addressable (see formstand docs) */}`,
            ];
          }
          if (field.spec.kind === "array") {
            const entry = nestedByKey.get(field.name);
            return entry === undefined
              ? []
              : [
                  `      <${entry.stem}Rows p0={index}${optionsPropsAttrs(rowItemOptionsProps(entry.item))} />`,
                ];
          }
          return isScalarSpec(field.spec)
            ? []
            : [
                `      {/* TODO: nested ${field.spec.kind} ${commentText(q(`${section.key}.$\{index}.${field.name}`))} — extract a row component with its own hook */}`,
              ];
        })
      : [];

  const used = new Set<string>(["index", "onRemove", "field", "rows"]);
  const rowVars = itemLeaves.map((field) => {
    // camelIdent, not camelCase: these become const bindings, and a field
    // named "new"/"delete" would otherwise emit a reserved-word declaration.
    // Number leaves reserve their hoisted `${var}NumberProps` const too
    // (numberPropsBindings emits it next to the field hooks).
    const base =
      camelIdent(field.name).length === 0 ? "value" : camelIdent(field.name);
    const { varName, reserved } = allocateBindingVar(
      base,
      field.spec.kind === "number",
      used,
    );
    reserved.forEach((n) => used.add(n));
    return { field, varName };
  });

  // A discriminated-union item can't be bound at a dynamic array-row path
  // (useVariantField needs a static union path), so it emits no leaf control,
  // no scalar row binding, and no union-only builder import — just a TODO,
  // mirroring the single-file backend's unreachable-container handling.
  const scalarItem = isScalarSpec(spec.item);

  const rowSpecs =
    spec.item.kind === "object"
      ? itemLeaves.map((f) => f.spec)
      : scalarItem
        ? [spec.item]
        : [];

  const dynamicId = (name: string | undefined): string =>
    name === undefined
      ? `{\`${templateEscape(section.key)}.\${index}\`}`
      : `{\`${templateEscape(section.key)}.\${index}.${templateEscape(name)}\`}`;

  const rowBindings =
    spec.item.kind === "object"
      ? rowVars.map(
          ({ field, varName }) =>
            `  const ${varName} = ${naming.hook("Field")}(\`${templateEscape(section.key)}.\${index}.${templateEscape(field.name)}\`);`,
        )
      : scalarItem
        ? [
            `  const field = ${naming.hook("Field")}(\`${templateEscape(section.key)}.\${index}\`);`,
          ]
        : [];

  const rowBody =
    spec.item.kind === "object"
      ? [
          ...rowVars.flatMap(({ field, varName }) =>
            leafControl(
              ui,
              field.spec,
              varName,
              jsxText(field.label),
              dynamicId(field.name),
              "      ",
            ),
          ),
          ...itemExtras,
        ]
      : scalarItem
        ? leafControl(
            ui,
            spec.item,
            "field",
            jsxText(section.label),
            dynamicId(undefined),
            "      ",
          )
        : arrayItemEntry !== undefined
          ? [
              `      <${arrayItemEntry.stem}Rows p0={index}${optionsPropsAttrs(rowItemOptionsProps(arrayItemEntry.item))} />`,
            ]
          : [
              // A discriminated-union or tuple item can't bind at a dynamic
              // array-row path (useVariantField needs a static union path), so
              // it emits just a TODO.
              `      {/* TODO: array item is a ${spec.item.kind} — bind its fields by hand with ${naming.hook("VariantField")} (dynamic array-row paths aren't generated) */}`,
            ];

  const imports = mergeImports([
    ...rowSpecs.flatMap((s) => leafImports(ui, s)),
    ...shell.imports,
    // The outer wrapper is objectShell, so panel/collapsible chrome pulls
    // its own components in.
    ...objectSectionImports(ui, visual),
    ...allNestedParts.flatMap((part) => part.imports),
  ]);

  // useXField is only imported when a row actually binds a field: an
  // object/scalar item binds one, but a discriminated-union item binds
  // nothing (its row is a TODO), so importing it would be an unused import
  // that breaks a consumer's noUnusedLocals.
  const usesField = [
    ...rowBindings,
    ...allNestedParts.flatMap((part) => part.lines),
  ].some((line) => line.includes(`${naming.hook("Field")}(`));

  // Options props consumed anywhere in this section's rows (direct row
  // leaves and nested arrays alike): the section declares them, the Row
  // takes the full set, and each nested ref forwards its own subset.
  const rowOptionsProps = rowItemOptionsProps(spec.item);
  const sectionPropsTypeFields = [
    "heading?: string",
    ...optionsPropsTypeFields(rowOptionsProps),
  ];

  return {
    path: `sections/${section.componentName}.tsx`,
    content: [
      HEADER,
      ...imports,
      "import {",
      ...(usesField ? [`  ${naming.hook("Field")},`] : []),
      `  ${naming.hook("FieldArray")},`,
      `  ${naming.hook("IsDirty")},`,
      `  ${naming.hook("IsValid")},`,
      `} from "../hooks";`,
      `import type { ${naming.valuesType} } from "../types";`,
      "",
      `export type ${propsType} = Readonly<{ ${sectionPropsTypeFields.join("; ")} }>;`,
      "",
      "// The array section's hook carries the field array alongside the",
      "// path-scoped flags; row fields bind template paths, so they stay",
      "// schema-typed.",
      `export const ${hookName} = () => ({`,
      `  rows: ${naming.hook("FieldArray")}(${q(section.key)}),`,
      `  dirty: ${naming.hook("IsDirty")}(${q(section.key)}),`,
      `  valid: ${naming.hook("IsValid")}(${q(section.key)}),`,
      "});",
      "",
      blankNeedsCast(spec.item)
        ? `const ${emptyName} = ${emitInitialValues(spec.item, 0)} as unknown as NonNullable<${naming.valuesType}[${q(section.key)}]>[number];`
        : `const ${emptyName}: NonNullable<${naming.valuesType}[${q(section.key)}]>[number] = ${emitInitialValues(spec.item, 0)};`,
      "",
      ...allNestedParts.flatMap((part) => [...part.lines, ""]),
      `const ${rowName} = ({`,
      "  index,",
      "  onRemove,",
      ...rowOptionsProps.map((name) => `  ${name},`),
      `}: Readonly<{ ${["index: number", "onRemove: () => void", ...optionsPropsTypeFields(rowOptionsProps)].join("; ")} }>) => {`,
      ...rowBindings,
      ...numberPropsBindings(
        ui,
        spec.item.kind === "object"
          ? rowVars.map(({ field, varName }) => ({
              varName,
              spec: field.spec,
            }))
          : scalarItem
            ? [{ varName: "field", spec: spec.item }]
            : [],
      ),
      "  return (",
      ...shell.rowOpen,
      ...rowBody,
      ...shell.rowClose("onRemove"),
      "  );",
      "};",
      "",
      `export const ${section.componentName} = ({`,
      `  heading = ${q(section.label)},`,
      ...rowOptionsProps.map((name) => `  ${name},`),
      `}: ${propsType}) => {`,
      `  const { rows, dirty, valid } = ${hookName}();`,
      "  return (",
      ...objectShell(ui, visual, [
        "      {rows.fields.map((row, index) => (",
        `        <${rowName}`,
        "          key={row.id}",
        "          index={index}",
        "          onRemove={() => rows.remove(index)}",
        ...rowOptionsProps.map((name) => `          ${name}={${name}}`),
        "        />",
        "      ))}",
        ...shell.listError,
        ...shell.addButton(
          `() => rows.push(${emptyName})`,
          `Add ${section.label.toLowerCase()}`,
        ),
      ]),
      "  );",
      "};",
      "",
    ].join("\n"),
  };
};

// The form component under the scaffold modes: --form-prop swaps the
// singleton import for a typed `form` prop (the submit/subscription shell
// runs on the prop; the field hooks stay pre-wired to the module's own
// instance, so the prop must BE that instance — documented in the emitted
// props comment), and --live swaps the submit scaffold for an optional
// onValuesChange subscription over form.watchValues (formstand >= 0.2;
// useFormValues is the post-0.12 render-side spelling).
const formFile = (
  ui: ModuleUi,
  naming: Naming,
  root: ObjectSpec,
  plan: Plan,
  scaffold: ScaffoldOptions,
): ModuleFile => {
  const shell = formShell(ui);
  const formExpr = scaffold.formProp ? "form" : naming.formConst;
  const shellImports = scaffold.live
    ? importsSansButton(shell.imports)
    : shell.imports;
  const propsType = `${naming.formName}Props`;
  // Options props (config-fields autocomplete overrides with optionsProp):
  // the page supplies each suggestion list here, and the form body threads
  // it down to the section/field that consumes it.
  const optionsProps = collectOptionsProps(root);
  const params = [
    ...(scaffold.formProp ? ["form"] : []),
    ...(scaffold.live ? ["onValuesChange"] : []),
    ...optionsProps.map((entry) => entry.name),
  ];
  const propsFields = [
    ...(scaffold.formProp
      ? [
          `  // The module's field hooks are pre-wired to ${naming.formConst}`,
          '  // (exported from "./hooks"): pass that instance. A different form',
          "  // of the same schema would compile, but the fields would keep",
          "  // reading the module's own form.",
          `  form: Form<${naming.schemaType}>;`,
        ]
      : []),
    ...(scaffold.live
      ? [
          "  // Fires on every value change (values are replaced immutably, so",
          "  // reference identity tracks real changes) — drive a map, a",
          "  // preview, or an autosave from here.",
          `  onValuesChange?: (values: ${naming.valuesType}) => void;`,
        ]
      : []),
    ...optionsProps.flatMap((entry) => [
      `  // Suggestions for the ${q(entry.path)} autocomplete override.`,
      `  ${entry.name}: readonly string[];`,
    ]),
  ];
  const typeImports = [
    ...(scaffold.formProp ? [naming.schemaType] : []),
    ...(scaffold.live ? [naming.valuesType] : []),
  ];
  // --form-prop still imports the singleton — not for the shell (that runs
  // on the prop) but for the dev-mode split-brain guard below.
  const hooksImports = scaffold.formProp
    ? [naming.formConst]
    : [naming.formConst, ...(scaffold.live ? [] : [naming.hook("IsSubmitting")])];
  return {
    path: `${naming.formName}.tsx`,
    content: [
      HEADER,
      ...(scaffold.live ? [`import { useEffect } from "react";`] : []),
      ...mergeImports(shellImports),
      // --form-prop runs the shell on the passed form, so useIsSubmitting
      // comes generic from the library instead of pre-wired from ./hooks.
      ...(scaffold.formProp && !scaffold.live
        ? [`import { useIsSubmitting, type Form } from "formstand";`]
        : scaffold.formProp
          ? [`import type { Form } from "formstand";`]
          : []),
      ...(hooksImports.length > 0
        ? [`import { ${hooksImports.join(", ")} } from "./hooks";`]
        : []),
      ...(typeImports.length > 0
        ? [`import type { ${typeImports.join(", ")} } from "./types";`]
        : []),
      ...plan.rootFields.map(
        (field) =>
          `import { ${field.componentName} } from "./fields/${field.componentName}";`,
      ),
      ...plan.sections.map(
        (section) =>
          `import { ${section.componentName} } from "./sections/${section.componentName}";`,
      ),
      "",
      ...(propsFields.length > 0
        ? [`export type ${propsType} = Readonly<{`, ...propsFields, "}>;", ""]
        : []),
      "// The form body composes sections; sections compose fields; fields bind",
      ...(scaffold.formProp
        ? [
            "// paths through the pre-wired hooks from ./hooks — the `form` prop",
            "// only drives this shell, so it must be the module's own instance.",
          ]
        : [
            "// paths. Nothing in this tree passes `form` — every hook comes pre-wired",
            "// from ./hooks.",
          ]),
      `export const ${naming.formName} = (${
        params.length === 0 ? "" : `{ ${params.join(", ")} }: ${propsType}`
      }) => {`,
      ...(scaffold.formProp
        ? [
            "  // Dev-mode split-brain guard: the field hooks are pre-wired to",
            `  // ${naming.formConst}, so a different form of the same schema would`,
            "  // compile but silently split state (the shell reads the prop, the",
            "  // fields keep reading the module's own form).",
            "  if (",
            '    typeof process !== "undefined" &&',
            '    process.env["NODE_ENV"] !== "production" &&',
            `    form !== ${naming.formConst}`,
            "  ) {",
            "    console.warn(",
            `      ${q(
              `${naming.formName}: the passed form is not this module's own instance from ./hooks — fields are pre-wired to the module form, so state will split. Pass ${naming.formConst} (see ${propsType} docs).`,
            )},`,
            "    );",
            "  }",
          ]
        : []),
      ...(scaffold.live
        ? []
        : scaffold.formProp
          ? ["  const submitting = useIsSubmitting(form);"]
          : [`  const submitting = ${naming.hook("IsSubmitting")}();`]),
      ...(scaffold.live
        ? [
            `  // ${formExpr}.watchValues (formstand >= 0.2) returns its own`,
            "  // unsubscribe. On formstand > 0.12, useFormValues is the",
            "  // render-side one-liner for the same subscription.",
            "  useEffect(",
            "    () =>",
            "      onValuesChange === undefined",
            "        ? undefined",
            `        : ${formExpr}.watchValues(onValuesChange),`,
            // The singleton is module-scoped (stable), so only the prop-form
            // variant lists it as a dependency.
            scaffold.formProp
              ? "    [form, onValuesChange],"
              : "    [onValuesChange],",
            "  );",
          ]
        : []),
      "  return (",
      ...shell.open,
      ...onSubmitAttrLines(formExpr, scaffold.live),
      ...shell.afterSubmit,
      ...plan.rootTodos.map((todo) => `${shell.bodyIndent}${todo}`),
      ...plan.rootFields.map(
        (field) =>
          `${shell.bodyIndent}<${field.componentName}${optionsPropsAttrs(leafOptionsProp(field.spec))} />`,
      ),
      ...plan.sections.map(
        (section) =>
          `${shell.bodyIndent}<${section.componentName}${optionsPropsAttrs(sectionOptionsProps(section.spec))} />`,
      ),
      ...(scaffold.live ? [] : shell.submitButton),
      ...shell.close,
      "  );",
      "};",
      "",
    ].join("\n"),
  };
};

