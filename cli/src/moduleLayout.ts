// Kit NUMBER controls bind through a useState-backed raw-text HOOK (see
// codegen's numberTextHook — typing "85000.50" must not reparse to
// "8500050" mid-entry), so every component that renders one hoists
// `const ${var}NumberProps = use<Kit>Number...Props(${var});` next to its
// field hooks, and leafJsx spreads the hoisted const. plain and shadcn keep
// their stateless builders (type="number" inputs).
const numberPropsHookName = (ui: ModuleUi): string | undefined => {
  switch (ui) {
    case "plain":
    case "shadcn":
      return undefined;
    case "mui":
    case "chakra":
    case "mantine":
    case "antd":
      return kitScalarBinding(ui, "number");
  }
};

// The hoist lines for every number-kind var in `vars` (empty for kits with
// stateless number builders). Callers splice these right after the field
// hook declarations they wrap.
const numberPropsBindings = (
  ui: ModuleUi,
  vars: readonly Readonly<{ varName: string; spec: FieldSpec }>[],
): readonly string[] => {
  const hook = numberPropsHookName(ui);
  return hook === undefined
    ? []
    : vars
        .filter(({ spec }) => spec.kind === "number")
        .map(
          ({ varName }) =>
            `  const ${varName}NumberProps = ${hook}(${varName});`,
        );
};

// The labeled control for one leaf bound to `varName`, at `indent`.
// `labelAttr` is a JSX expression container string (e.g. `{label}` or
// `{"Email"}`); `idAttr` likewise, or undefined where the kit needs none.
const leafJsx = (
  ui: ModuleUi,
  spec: FieldSpec,
  varName: string,
  labelAttr: string,
  idAttr: string | undefined,
  indent: string,
): readonly string[] => {
  switch (ui) {
    case "plain": {
      const control =
        spec.kind === "enum"
          ? [
              `${indent}    <select {...selectProps(${varName})}>`,
              `${indent}      <option value="">{"Select…"}</option>`,
              ...spec.options.map(
                (option) =>
                  `${indent}      <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
              ),
              `${indent}    </select>`,
            ]
          : [
              `${indent}    <input {...${
                spec.kind === "number"
                  ? "numberInputProps"
                  : spec.kind === "boolean"
                    ? "checkboxProps"
                    : spec.kind === "date"
                      ? "dateInputProps"
                      : "textInputProps"
              }(${varName})} />`,
            ];
      return [
        `${indent}<div>`,
        `${indent}  <label>`,
        `${indent}    ${labelAttr}`,
        ...control,
        `${indent}  </label>`,
        `${indent}  {${varName}.error?.[0] !== undefined ? (`,
        `${indent}    <p role="alert">{${varName}.error?.[0]}</p>`,
        `${indent}  ) : null}`,
        `${indent}</div>`,
      ];
    }
    case "mui":
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<FormControlLabel`,
            `${indent}  label=${labelAttr}`,
            `${indent}  control={<Switch {...muiSwitchProps(${varName})} />}`,
            `${indent}/>`,
          ];
        case "enum":
          return [
            `${indent}<TextField select fullWidth label=${labelAttr} {...muiSelectProps(${varName})}>`,
            ...spec.options.map(
              (option) =>
                `${indent}  <MenuItem value=${jsxText(option)}>${jsxText(labelFromName(option))}</MenuItem>`,
            ),
            `${indent}</TextField>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${varName}NumberProps} />`,
          ];
        case "date":
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${kitScalarBinding("mui", "date")}(${varName})} />`,
          ];
        default:
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${kitScalarBinding("mui", "string")}(${varName})} />`,
          ];
      }
    case "mantine":
      // Mantine controls wire their own label/error/ids internally (error
      // rides in the adapter builders), so no id attribute is needed.
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Switch label=${labelAttr} {...mantineSwitchProps(${varName})} />`,
          ];
        case "enum":
          return [
            `${indent}<NativeSelect label=${labelAttr} {...mantineSelectProps(${varName})}>`,
            `${indent}  <option value="">{"Select…"}</option>`,
            ...spec.options.map(
              (option) =>
                `${indent}  <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
            ),
            `${indent}</NativeSelect>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<TextInput label=${labelAttr} {...${varName}NumberProps} />`,
          ];
        default: {
          const builder = kitScalarBinding(
            "mantine",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<TextInput label=${labelAttr} {...${builder}(${varName})} />`,
          ];
        }
      }
    case "antd": {
      // antd's error slot lives in Form.Item, which the generated code
      // never uses (formstand owns state) — so leaves render an explicit
      // label/control/FieldError column; ids wire the plain <label>.
      const id = idAttr ?? `{${q("")}}`;
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Checkbox {...antdCheckboxProps(${varName})}>${labelAttr}</Checkbox>`,
          ];
        case "enum":
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Select`,
            `${indent}    id=${id}`,
            `${indent}    placeholder=${labelAttr}`,
            `${indent}    options={[`,
            ...spec.options.map(
              (option) =>
                `${indent}      { value: ${q(option)}, label: ${q(labelFromName(option))} },`,
            ),
            `${indent}    ]}`,
            `${indent}    {...antdSelectProps(${varName})}`,
            `${indent}  />`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Input id=${id} {...${varName}NumberProps} />`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "antd",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Input id=${id} {...${builder}(${varName})} />`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        }
      }
    }
    case "chakra":
      // Chakra 3 compound parts: Field.Root wires ids/aria between Label,
      // control, and ErrorText via context, so no id attribute is needed.
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Switch.Root {...chakraSwitchProps(${varName})}>`,
            `${indent}  <Switch.HiddenInput />`,
            `${indent}  <Switch.Control>`,
            `${indent}    <Switch.Thumb />`,
            `${indent}  </Switch.Control>`,
            `${indent}  <Switch.Label>${labelAttr}</Switch.Label>`,
            `${indent}</Switch.Root>`,
          ];
        case "enum":
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <NativeSelect.Root>`,
            `${indent}    <NativeSelect.Field placeholder=${labelAttr} {...chakraSelectProps(${varName})}>`,
            ...spec.options.map(
              (option) =>
                `${indent}      <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
            ),
            `${indent}    </NativeSelect.Field>`,
            `${indent}    <NativeSelect.Indicator />`,
            `${indent}  </NativeSelect.Root>`,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <Input {...${varName}NumberProps} />`,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "chakra",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <Input {...${builder}(${varName})} />`,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        }
      }
    case "shadcn": {
      const id = idAttr ?? `{${q("")}}`;
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <div className="flex items-center gap-2">`,
            `${indent}    <Checkbox id=${id} {...shadcnCheckboxProps(${varName})} />`,
            `${indent}    <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  </div>`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        case "enum":
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  <Select {...shadcnSelectProps(${varName})}>`,
            `${indent}    <SelectTrigger`,
            `${indent}      id=${id}`,
            `${indent}      className="w-full"`,
            `${indent}      aria-invalid={ariaInvalid(${varName})}`,
            `${indent}    >`,
            `${indent}      <SelectValue placeholder=${labelAttr} />`,
            `${indent}    </SelectTrigger>`,
            `${indent}    <SelectContent>`,
            ...spec.options.map(
              (option) =>
                `${indent}      <SelectItem value=${jsxText(option)}>${jsxText(labelFromName(option))}</SelectItem>`,
            ),
            `${indent}    </SelectContent>`,
            `${indent}  </Select>`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "shadcn",
            spec.kind === "number"
              ? "number"
              : spec.kind === "date"
                ? "date"
                : "string",
          );
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  <Input id=${id} {...${builder}(${varName})} />`,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        }
      }
    }
  }
};

