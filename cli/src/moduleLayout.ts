// Kit NUMBER controls bind through a useState-backed raw-text HOOK (see
// codegen's numberTextHook — typing "85000.50" must not reparse to
// "8500050" mid-entry), so every component that renders one hoists
// `const ${var}NumberProps = use<Kit>Number...Props(${var});` next to its
// field hooks, and leafJsx spreads the hoisted const. plain and shadcn keep
// their stateless builders (type="number" inputs).
const numberPropsHookName = (ui: ModuleUi): string | undefined => {
  switch (ui) {
    case "plain":
    case "shadcn":
      return undefined;
    case "mui":
    case "chakra":
    case "mantine":
    case "antd":
      return kitScalarBinding(ui, "number");
  }
};

// The hoist lines for every number-kind var in `vars` (empty for kits with
// stateless number builders). Callers splice these right after the field
// hook declarations they wrap.
const numberPropsBindings = (
  ui: ModuleUi,
  vars: readonly Readonly<{ varName: string; spec: FieldSpec }>[],
): readonly string[] => {
  const hook = numberPropsHookName(ui);
  return hook === undefined
    ? []
    : vars
        .filter(({ spec }) => spec.kind === "number")
        .map(
          ({ varName }) =>
            `  const ${varName}NumberProps = ${hook}(${varName});`,
        );
};

// The autocomplete-override control, bound to `varName` — the module-layout
// twin of the single-file Bound autocomplete components (same per-kit
// bindings: MUI Autocomplete freeSolo on the input value, Mantine
// Autocomplete, antd AutoComplete, plain/shadcn/chakra Input + native
// <datalist>). The datalist id derives from the bound path at runtime, so
// array rows each get their own list.
const autocompleteLeafJsx = (
  ui: ModuleUi,
  spec: FieldSpec,
  varName: string,
  labelAttr: string,
  idAttr: string | undefined,
  indent: string,
): readonly string[] => {
  const optionsExpr = autocompleteOptionsExpr(spec);
  const listAttr = `{\`\${${varName}.path}-datalist\`}`;
  const datalist = [
    `${indent}  <datalist id=${listAttr}>`,
    `${indent}    {${optionsExpr}.map((option) => (`,
    `${indent}      <option key={option} value={option} />`,
    `${indent}    ))}`,
    `${indent}  </datalist>`,
  ];
  switch (ui) {
    case "plain": {
      const desc =
        spec.description !== undefined
          ? [
              `${indent}  <p className="zf-help">${jsxText(spec.description)}</p>`,
            ]
          : [];
      return [
        `${indent}<div>`,
        `${indent}  <label>`,
        `${indent}    ${labelAttr}`,
        `${indent}    <input list=${listAttr} {...textInputProps(${varName})} />`,
        `${indent}  </label>`,
        ...datalist,
        ...desc,
        `${indent}  {${varName}.error?.[0] !== undefined ? (`,
        `${indent}    <p role="alert">{${varName}.error?.[0]}</p>`,
        `${indent}  ) : null}`,
        `${indent}</div>`,
      ];
    }
    case "mui":
      return [
        `${indent}<Autocomplete`,
        `${indent}  fullWidth`,
        `${indent}  {...muiAutocompleteProps(${varName})}`,
        `${indent}  options={${optionsExpr}}`,
        `${indent}  renderInput={(params) => (`,
        `${indent}    <TextField`,
        `${indent}      // The canonical MUI pattern. The cast is for`,
        `${indent}      // @mui/material 5/6 only: their params typing trips`,
        `${indent}      // exactOptionalPropertyTypes consumers; 7/9 accept`,
        `${indent}      // the spread as-is.`,
        `${indent}      {...(params as unknown as TextFieldProps)}`,
        `${indent}      label=${labelAttr}`,
        `${indent}      name={${varName}.path}`,
        `${indent}      error={fieldError(${varName}) !== undefined}`,
        spec.description !== undefined
          ? `${indent}      helperText={fieldError(${varName}) ?? ${q(spec.description)}}`
          : `${indent}      helperText={fieldError(${varName})}`,
        `${indent}    />`,
        `${indent}  )}`,
        `${indent}/>`,
      ];
    case "mantine": {
      const descAttr =
        spec.description !== undefined
          ? ` description=${jsxText(spec.description)}`
          : "";
      return [
        `${indent}<Autocomplete label=${labelAttr}${descAttr} data={${optionsExpr}} {...mantineAutocompleteProps(${varName})} />`,
      ];
    }
    case "antd": {
      const id = idAttr ?? `{${q("")}}`;
      const descLines =
        spec.description !== undefined
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <Typography.Text type="secondary">${jsxText(spec.description)}</Typography.Text>`,
              `${indent}  ) : null}`,
            ]
          : [];
      return [
        `${indent}<Flex vertical gap="small">`,
        `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
        `${indent}  <AutoComplete`,
        `${indent}    id=${id}`,
        `${indent}    options={${optionsExpr}.map((option) => ({ value: option }))}`,
        `${indent}    {...antdAutoCompleteProps(${varName})}`,
        `${indent}  />`,
        ...descLines,
        `${indent}  <FieldError field={${varName}} />`,
        `${indent}</Flex>`,
      ];
    }
    case "chakra": {
      const descLines =
        spec.description !== undefined
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <Field.HelperText>${jsxText(spec.description)}</Field.HelperText>`,
              `${indent}  ) : null}`,
            ]
          : [];
      return [
        `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
        `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
        `${indent}  <Input list=${listAttr} {...chakraTextInputProps(${varName})} />`,
        ...datalist,
        ...descLines,
        `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
        `${indent}</Field.Root>`,
      ];
    }
    case "shadcn": {
      const id = idAttr ?? `{${q("")}}`;
      const descLines =
        spec.description !== undefined
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <p className="text-sm text-muted-foreground">${jsxText(spec.description)}</p>`,
              `${indent}  ) : null}`,
            ]
          : [];
      return [
        `${indent}<div className="grid gap-2">`,
        `${indent}  <Label htmlFor=${id}>${labelAttr}</Label>`,
        `${indent}  <Input id=${id} list=${listAttr} {...shadcnTextInputProps(${varName})} />`,
        ...datalist,
        ...descLines,
        `${indent}  <FieldError field={${varName}} />`,
        `${indent}</div>`,
      ];
    }
  }
};

// The labeled control for one leaf bound to `varName`, at `indent`.
// `labelAttr` is a JSX expression container string (e.g. `{label}` or
// `{"Email"}`); `idAttr` likewise, or undefined where the kit needs none.
const leafJsx = (
  ui: ModuleUi,
  spec: FieldSpec,
  varName: string,
  labelAttr: string,
  idAttr: string | undefined,
  indent: string,
): readonly string[] => {
  // The autocomplete override swaps the whole control, string or enum.
  if (isAutocompleteLeaf(spec)) {
    return autocompleteLeafJsx(ui, spec, varName, labelAttr, idAttr, indent);
  }
  switch (ui) {
    case "plain": {
      const control =
        spec.kind === "enum"
          ? [
              `${indent}    <select {...selectProps(${varName})}>`,
              `${indent}      <option value="">{"Select…"}</option>`,
              ...spec.options.map(
                (option) =>
                  `${indent}      <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
              ),
              `${indent}    </select>`,
            ]
          : [
              `${indent}    <input {...${
                spec.kind === "number"
                  ? "numberInputProps"
                  : spec.kind === "boolean"
                    ? "checkboxProps"
                    : spec.kind === "date"
                      ? "dateInputProps"
                      : "textInputProps"
              }(${varName})} />`,
            ];
      // The always-visible muted helper line — plain keeps the description
      // in its own slot next to the error line (mirrors the single-file
      // backend's plainLeaf policy and its "zf-help" styling hook).
      const desc =
        spec.description !== undefined
          ? [
              `${indent}  <p className="zf-help">${jsxText(spec.description)}</p>`,
            ]
          : [];
      return [
        `${indent}<div>`,
        `${indent}  <label>`,
        `${indent}    ${labelAttr}`,
        ...control,
        `${indent}  </label>`,
        ...desc,
        `${indent}  {${varName}.error?.[0] !== undefined ? (`,
        `${indent}    <p role="alert">{${varName}.error?.[0]}</p>`,
        `${indent}  ) : null}`,
        `${indent}</div>`,
      ];
    }
    case "mui": {
      // A described leaf inlines its literal into MUI's one helper-text slot
      // after the adapter spread — the error keeps the slot while present
      // (same swap as the single-file backend).
      const helper =
        spec.description !== undefined &&
        describedLeafKinds("mui").has(spec.kind)
          ? ` helperText={fieldError(${varName}) ?? ${q(spec.description)}}`
          : "";
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<FormControlLabel`,
            `${indent}  label=${labelAttr}`,
            `${indent}  control={<Switch {...muiSwitchProps(${varName})} />}`,
            `${indent}/>`,
          ];
        case "enum":
          return [
            `${indent}<TextField select fullWidth label=${labelAttr} {...muiSelectProps(${varName})}${helper}>`,
            ...spec.options.map(
              (option) =>
                `${indent}  <MenuItem value=${jsxText(option)}>${jsxText(labelFromName(option))}</MenuItem>`,
            ),
            `${indent}</TextField>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${varName}NumberProps}${helper} />`,
          ];
        case "date":
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${kitScalarBinding("mui", "date")}(${varName})}${helper} />`,
          ];
        default:
          return [
            `${indent}<TextField fullWidth label=${labelAttr} {...${kitScalarBinding("mui", "string")}(${varName})}${helper} />`,
          ];
      }
    }
    case "mantine": {
      // Mantine controls wire their own label/error/ids internally (error
      // rides in the adapter builders), so no id attribute is needed. A
      // described leaf fills the native `description` slot — its own
      // element, separate from the error slot, so no swap is emitted.
      const descAttr =
        spec.description !== undefined
          ? ` description=${jsxText(spec.description)}`
          : "";
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Switch label=${labelAttr}${descAttr} {...mantineSwitchProps(${varName})} />`,
          ];
        case "enum":
          return [
            `${indent}<NativeSelect label=${labelAttr}${descAttr} {...mantineSelectProps(${varName})}>`,
            `${indent}  <option value="">{"Select…"}</option>`,
            ...spec.options.map(
              (option) =>
                `${indent}  <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
            ),
            `${indent}</NativeSelect>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<TextInput label=${labelAttr}${descAttr} {...${varName}NumberProps} />`,
          ];
        default: {
          const builder = kitScalarBinding(
            "mantine",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<TextInput label=${labelAttr}${descAttr} {...${builder}(${varName})} />`,
          ];
        }
      }
    }
    case "antd": {
      // antd's error slot lives in Form.Item, which the generated code
      // never uses (formstand owns state) — so leaves render an explicit
      // label/control/FieldError column; ids wire the plain <label>. A
      // described leaf adds the muted Typography.Text line, rendered only
      // while the FieldError line is not (the two share the one slot).
      const id = idAttr ?? `{${q("")}}`;
      const descLines =
        spec.description !== undefined &&
        describedLeafKinds("antd").has(spec.kind)
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <Typography.Text type="secondary">${jsxText(spec.description)}</Typography.Text>`,
              `${indent}  ) : null}`,
            ]
          : [];
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Checkbox {...antdCheckboxProps(${varName})}>${labelAttr}</Checkbox>`,
          ];
        case "enum":
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Select`,
            `${indent}    id=${id}`,
            `${indent}    placeholder=${labelAttr}`,
            `${indent}    options={[`,
            ...spec.options.map(
              (option) =>
                `${indent}      { value: ${q(option)}, label: ${q(labelFromName(option))} },`,
            ),
            `${indent}    ]}`,
            `${indent}    {...antdSelectProps(${varName})}`,
            `${indent}  />`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Input id=${id} {...${varName}NumberProps} />`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "antd",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<Flex vertical gap="small">`,
            `${indent}  <label htmlFor=${id}>${labelAttr}</label>`,
            `${indent}  <Input id=${id} {...${builder}(${varName})} />`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</Flex>`,
          ];
        }
      }
    }
    case "chakra": {
      // Chakra 3 compound parts: Field.Root wires ids/aria between Label,
      // control, and ErrorText via context, so no id attribute is needed. A
      // described leaf renders Field.HelperText only while Field.ErrorText
      // does not (chakra shows both otherwise — the swap is explicit).
      const descLines =
        spec.description !== undefined &&
        describedLeafKinds("chakra").has(spec.kind)
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <Field.HelperText>${jsxText(spec.description)}</Field.HelperText>`,
              `${indent}  ) : null}`,
            ]
          : [];
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<Switch.Root {...chakraSwitchProps(${varName})}>`,
            `${indent}  <Switch.HiddenInput />`,
            `${indent}  <Switch.Control>`,
            `${indent}    <Switch.Thumb />`,
            `${indent}  </Switch.Control>`,
            `${indent}  <Switch.Label>${labelAttr}</Switch.Label>`,
            `${indent}</Switch.Root>`,
          ];
        case "enum":
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <NativeSelect.Root>`,
            `${indent}    <NativeSelect.Field placeholder=${labelAttr} {...chakraSelectProps(${varName})}>`,
            ...spec.options.map(
              (option) =>
                `${indent}      <option value=${jsxText(option)}>${jsxText(labelFromName(option))}</option>`,
            ),
            `${indent}    </NativeSelect.Field>`,
            `${indent}    <NativeSelect.Indicator />`,
            `${indent}  </NativeSelect.Root>`,
            ...descLines,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        // Spread from the hoisted `${var}NumberProps` const — the number
        // binding is a hook (see numberPropsBindings).
        case "number":
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <Input {...${varName}NumberProps} />`,
            ...descLines,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "chakra",
            spec.kind === "date" ? "date" : "string",
          );
          return [
            `${indent}<Field.Root invalid={fieldError(${varName}) !== undefined}>`,
            `${indent}  <Field.Label>${labelAttr}</Field.Label>`,
            `${indent}  <Input {...${builder}(${varName})} />`,
            ...descLines,
            `${indent}  <Field.ErrorText>{fieldError(${varName})}</Field.ErrorText>`,
            `${indent}</Field.Root>`,
          ];
        }
      }
    }
    case "shadcn": {
      // The muted description line shares the under-control slot with the
      // FieldError line — the error wins it while present.
      const id = idAttr ?? `{${q("")}}`;
      const descLines =
        spec.description !== undefined
          ? [
              `${indent}  {fieldError(${varName}) === undefined ? (`,
              `${indent}    <p className="text-sm text-muted-foreground">${jsxText(spec.description)}</p>`,
              `${indent}  ) : null}`,
            ]
          : [];
      switch (spec.kind) {
        case "boolean":
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <div className="flex items-center gap-2">`,
            `${indent}    <Checkbox id=${id} {...shadcnCheckboxProps(${varName})} />`,
            `${indent}    <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  </div>`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        case "enum":
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  <Select {...shadcnSelectProps(${varName})}>`,
            `${indent}    <SelectTrigger`,
            `${indent}      id=${id}`,
            `${indent}      className="w-full"`,
            `${indent}      aria-invalid={ariaInvalid(${varName})}`,
            `${indent}    >`,
            `${indent}      <SelectValue placeholder=${labelAttr} />`,
            `${indent}    </SelectTrigger>`,
            `${indent}    <SelectContent>`,
            ...spec.options.map(
              (option) =>
                `${indent}      <SelectItem value=${jsxText(option)}>${jsxText(labelFromName(option))}</SelectItem>`,
            ),
            `${indent}    </SelectContent>`,
            `${indent}  </Select>`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        default: {
          const builder = kitScalarBinding(
            "shadcn",
            spec.kind === "number"
              ? "number"
              : spec.kind === "date"
                ? "date"
                : "string",
          );
          return [
            `${indent}<div className="grid gap-2">`,
            `${indent}  <Label htmlFor=${id}>${labelAttr}</Label>`,
            `${indent}  <Input id=${id} {...${builder}(${varName})} />`,
            ...descLines,
            `${indent}  <FieldError field={${varName}} />`,
            `${indent}</div>`,
          ];
        }
      }
    }
  }
};

// Same, prefixed with JSX-comment TODOs — safe only in child position
// (a comment container can't precede the return expression itself).
const leafControl = (
  ui: ModuleUi,
  spec: FieldSpec,
  varName: string,
  labelAttr: string,
  idAttr: string | undefined,
  indent: string,
): readonly string[] => [
  ...todoTexts(spec).map((text) => `${indent}{/* TODO: ${text} */}`),
  // The override-site documentation comment (same production as the
  // single-file backends).
  ...(isAutocompleteLeaf(spec)
    ? [`${indent}{/* ${autocompleteSiteComment(spec)} */}`]
    : []),
  ...leafJsx(ui, spec, varName, labelAttr, idAttr, indent),
];

