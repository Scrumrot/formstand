const hooksFile = (
  naming: Naming,
  schemaImport: SchemaImport,
  root: ObjectSpec,
  plan: Plan,
  scaffold: ScaffoldOptions,
): ModuleFile => {
  // Nested arrays (under object sections, or inside array rows) bind the
  // same bound hooks as top-level array sections, so look past the roots.
  const hasArrays = root.fields.some(
    (field) => !isUnaddressable(field.name) && specHasArray(field.spec),
  );
  // A union renders a discriminant + common fields (useField) and its
  // variant-only fields (useVariantField), so useField joins the API for any
  // union, but useVariantField only when a variant-only field exists (a union
  // of only common keys — e.g. a single-variant union — never emits one).
  const hasUnions = root.fields.some(
    (field) => !isUnaddressable(field.name) && specHasUnion(field.spec),
  );
  const hasVariantFields = root.fields.some(
    (field) => !isUnaddressable(field.name) && hasVariantFieldUsage(field.spec),
  );
  const hasFields = plan.fields.length > 0 || hasArrays || hasUnions;
  const hooks = [
    ...(hasFields ? [naming.hook("Field")] : []),
    ...(hasVariantFields ? [naming.hook("VariantField")] : []),
    ...(hasArrays ? [naming.hook("FieldArray")] : []),
    ...(plan.sections.length > 0
      ? [naming.hook("IsDirty"), naming.hook("IsValid")]
      : []),
    naming.hook("IsSubmitting"),
  ];
  return {
    path: "hooks.ts",
    content: [
      HEADER,
      `import { createForm, createFormHooks } from "formstand";`,
      `import { ${schemaImport.name} } from "./schema";`,
      `import type { ${naming.valuesType} } from "./types";`,
      "",
      ...(blankNeedsCast(root)
        ? [
            "// A form starts blank: required numbers/dates/enums begin",
            "// undefined (and any TODO-degraded placeholder field starts as a",
            "// blank guess), so these initial values intentionally do not",
            "// satisfy the schema yet; hence the cast. Validation reports the",
            "// gaps on submit.",
            `const initialValues = ${emitInitialValues(root, 0)} as unknown as ${naming.valuesType};`,
          ]
        : [
            "// A form starts blank, and every field here has a legal blank",
            '// state (strings "", booleans false, optional/nullable',
            "// undefined/null), so the draft typechecks as-is; no cast needed.",
            `const initialValues: ${naming.valuesType} = ${emitInitialValues(root, 0)};`,
          ]),
      "",
      "// One module-level form for the whole feature; every file below imports",
      "// these pre-wired hooks instead of receiving `form` via props or a",
      "// provider. A module singleton never unmounts — for a per-mount",
      "// lifecycle, use useForm + createFormContext instead.",
      ...(scaffold.live
        ? [
            `// --live: mode "onChange" (not the library default "onBlur") so`,
            "// live subscribers never read values whose errors lag a blur",
            "// behind.",
          ]
        : []),
      `export const ${naming.formConst} = createForm(${schemaImport.name}, {`,
      "  initialValues,",
      `  mode: ${q(emittedMode(scaffold))},`,
      "});",
      "",
      "export const {",
      ...hooks.map((name) => `  ${name},`),
      `} = createFormHooks(${naming.formConst}, ${q(naming.factoryArg)});`,
      "",
    ].join("\n"),
  };
};

// The kit adapter the single-file backends inline, exported once — only for
// the kit uis, and only when some leaf actually renders a control. The mui
// adapter is the one spot the targeted @mui/material major changes emission
// (TextField's slot-props API), so the version threads to here and nowhere
// else in the module layout.
const adapterFile = (
  ui: ModuleUi,
  usage: KindUsage,
  muiVersion?: MuiVersion,
): ModuleFile | undefined => {
  if (!hasLeafUsage(usage)) return undefined;
  // Exhaustive over ModuleUi (like every sibling site): a future kit fails
  // to compile here instead of silently falling into another kit's adapter.
  const adapterSection = ((): string | undefined => {
    switch (ui) {
      case "plain":
        // plain binds through formstand's own prop builders — no adapter.
        return undefined;
      case "mui":
        return muiAdapterSection(usage, "export ", muiVersion);
      case "chakra":
        return chakraAdapterSection(usage, "export ");
      case "mantine":
        return mantineAdapterSection(usage, "export ");
      case "antd":
        return antdAdapterSection(usage, "export ");
      case "shadcn":
        return shadcnAdapterSection(usage, "export ");
    }
  })();
  if (adapterSection === undefined) return undefined;
  const needsText = usage.string || usage.date;
  // mui's Switch adapter also types its onChange with ChangeEvent, so a
  // boolean-only schema needs the import too; chakra's select is a native
  // <select> (ChangeEvent), but its Switch takes a details callback;
  // mantine speaks DOM events everywhere (its Switch included); antd's
  // Select is value-shaped and its Checkbox speaks CheckboxChangeEvent, so
  // only the Input adapters (text/number/date) need ChangeEvent there.
  // The chakra/shadcn autocomplete override rides those kits' TEXT adapter
  // (Input + native datalist), so an autocomplete-only schema still emits
  // the ChangeEvent-typed builder there; mantine's and antd's autocomplete
  // adapters are value-shaped and mui's types SyntheticEvent (below).
  const needsChangeEvent =
    needsText ||
    usage.number ||
    (ui === "mui" && (usage.enum || usage.boolean)) ||
    (ui === "chakra" && (usage.enum || usage.autocomplete)) ||
    (ui === "shadcn" && usage.autocomplete) ||
    (ui === "mantine" && (usage.enum || usage.boolean));
  // The antd adapter's own imports: Typography renders the FieldError line
  // (gated with the error helpers on non-boolean usage — the autocomplete
  // override included, mirroring antdAdapterSection's needsError), and the
  // Checkbox adapter types its onChange with antd's own CheckboxChangeEvent.
  const antdImports =
    ui === "antd"
      ? [
          ...(usage.string ||
          usage.date ||
          usage.number ||
          usage.enum ||
          usage.autocomplete
            ? [`import { Typography } from "antd";`]
            : []),
          ...(usage.boolean
            ? [`import type { CheckboxChangeEvent } from "antd";`]
            : []),
        ]
      : [];
  return {
    // Only the shadcn and antd adapters render JSX (their FieldError
    // components); the other kit adapters are prop builders.
    path: ui === "shadcn" || ui === "antd" ? "adapter.tsx" : "adapter.ts",
    content: [
      HEADER,
      // The stateful number hook needs useState; shadcn's number binding
      // stays the stateless type="number" builder. The mui autocomplete
      // adapter types onInputChange's event with SyntheticEvent.
      ...reactImportLines(
        needsChangeEvent,
        usage.number && ui !== "shadcn",
        false,
        ui === "mui" && usage.autocomplete,
      ),
      ...antdImports,
      "import {",
      ...(usage.number ? ["  numberToInputText,", "  parseNumberText,"] : []),
      ...(usage.date ? ["  dateToInputText,", "  parseDateText,"] : []),
      "  type UseFieldReturn,",
      `} from "formstand";`,
      "",
      adapterSection,
      "",
    ].join("\n"),
  };
};

